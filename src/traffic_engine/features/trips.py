"""Виртуальные поездки: превращение срезов по датчикам во время в пути.

В PeMS нет колонки «поездка заняла столько-то минут». Есть скорость на
каждой станции в каждый пятиминутный интервал. Обучающую выборку надо
построить самим.

Метод. Для момента отправления ``t`` машина въезжает на первую станцию
коридора, по её скорости в момент ``t`` проезжает первый сегмент,
попадает на вторую станцию уже в момент ``t + Δ₁`` — и дальше скорость
берётся **на тот момент, когда машина туда доехала**, а не на момент
отправления. Сумма по всем сегментам и есть время поездки.

Сколько это даёт на самом деле
------------------------------
Наивная альтернатива — взять скорости на всех станциях одновременно, в
момент ``t``. Первоначально здесь было написано, что она «систематически
занижает время». **Проверка на январе 2026 это опровергла**, и честнее
оставить как есть, чем подгонять текст под ожидание.

На коридоре SR-210 West (9.3 мили, 8927 поездок) обе оценки совпадают
почти полностью:

===========  =====  =====  =====  =====
Метод        P50    P90    P95    средн
===========  =====  =====  =====  =====
честный      8.9    14.0   19.3   10.4
наивный      8.9    14.1   19.2   10.4
===========  =====  =====  =====  =====

Но совпадение это сводное, а не поточечное. Попарная разность даёт
нулевое среднее при стандартном отклонении 0.61 минуты и размахе от
−15.5 до +7.6. Разбор по фазе затора показывает, откуда что берётся:

=================  ==========  ====================
Что происходит      Поездок     Разность, мин
=================  ==========  ====================
затор быстро рос          158    **+1.79**
рос                       595    +0.22
ровно                    7312    −0.01
спадал                    773    −0.34
быстро спадал              83    **−1.17**
=================  ==========  ====================

То есть наивный метод ошибается **в обе стороны**: занижает, когда
затор нарастает, и завышает, когда рассасывается. В сводке эти ошибки
гасят друг друга — потому и вышло совпадение до второго знака.

Вывод для проекта: на коротком коридоре выбор метода почти ничего не
меняет, потому что поездка укладывается в два-четыре пятиминутных
интервала и обстановка не успевает измениться. Разница станет
существенной на длинном маршруте — на часовой поездке через весь Лос-
Анджелес утренняя волна успевает догнать машину.

Аккуратный метод оставлен по трём причинам: он не дороже, он не
разрывает последовательность сегментов (а именно связь между ними
делает хвост тяжёлым — см. README про сложение квантилей), и он
не ломается при переходе на длинные маршруты. Но выдавать его за
источник выигрыша на этих данных было бы неправдой.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

# Ниже этой скорости результат считается нефизичным: деление на почти
# ноль растягивает время поездки до бесконечности. PeMS при полной
# остановке пишет очень малые значения, и одна такая строка испортила бы
# всю поездку.
MIN_SPEED_MPH = 5.0

# Выше этой — тоже мусор: свободный ход на калифорнийском фривее не
# превышает семидесяти с небольшим.
MAX_SPEED_MPH = 90.0

SLOT_MINUTES = 5


def segment_lengths(postmiles: np.ndarray | list[float]) -> np.ndarray:
    """Длины сегментов между соседними станциями, мили.

    Абсолютные постмили убывают при движении на запад и на юг, поэтому
    берётся модуль разности: важна длина, а не знак.
    """
    pm = np.asarray(postmiles, dtype=float)
    if pm.ndim != 1 or pm.size < 2:
        raise ValueError("нужно хотя бы две станции")
    return np.abs(np.diff(pm))


def virtual_trips(
    speed: pd.DataFrame,
    postmiles: np.ndarray | list[float],
    *,
    slot_minutes: int = SLOT_MINUTES,
    min_speed: float = MIN_SPEED_MPH,
    max_speed: float = MAX_SPEED_MPH,
    simultaneous: bool = False,
) -> pd.Series:
    """Время проезда коридора для каждого момента отправления.

    Parameters
    ----------
    speed
        Таблица скоростей: строки — моменты времени с равномерным шагом
        ``slot_minutes``, столбцы — станции **в порядке движения**.
    postmiles
        Абсолютные постмили тех же станций, в том же порядке.
    simultaneous
        Считать наивным способом — все скорости берутся на момент
        отправления. Нужно только для сравнения: именно эту величину
        мы собираемся показать как заниженную.

    Returns
    -------
    pandas.Series
        Время в пути, минуты. ``NaN`` там, где поездка не помещается в
        имеющийся период (конец выборки) или упирается в пропуск
        скорости.

    Notes
    -----
    Требуется равномерная сетка времени без пропусков: положение
    «через сколько-то минут» вычисляется сдвигом строки, а не поиском
    по метке. Проверка на равномерность делается здесь же.
    """
    if speed.shape[1] < 2:
        raise ValueError("нужно хотя бы две станции")

    dt = speed.index.to_series().diff().dropna().unique()
    expected = pd.Timedelta(minutes=slot_minutes)
    if len(dt) != 1 or dt[0] != expected:
        raise ValueError(f"сетка времени неравномерна: ожидался шаг {expected}, найдено {dt[:3]}")

    v = np.clip(speed.to_numpy(dtype=float), min_speed, max_speed)
    n_slots, n_stations = v.shape
    seg = segment_lengths(postmiles)
    if seg.size != n_stations - 1:
        raise ValueError(f"{n_stations} станций, но {seg.size + 1} постмилей")

    departure = np.arange(n_slots)
    elapsed = np.zeros(n_slots, dtype=float)
    ok = np.ones(n_slots, dtype=bool)

    for k in range(n_stations - 1):
        if simultaneous:
            row = departure
        else:
            # на сколько целых интервалов машина продвинулась во времени
            row = departure + np.floor(elapsed / slot_minutes).astype(int)
        ok &= row < n_slots
        speed_here = v[np.clip(row, 0, n_slots - 1), k]
        ok &= ~np.isnan(speed_here)
        elapsed = elapsed + seg[k] / np.where(np.isnan(speed_here), 1.0, speed_here) * 60.0

    return pd.Series(np.where(ok, elapsed, np.nan), index=speed.index, name="travel_time_min")


def speed_matrix(
    df: pd.DataFrame,
    station_order: list[int],
    *,
    value: str = "avg_speed",
) -> pd.DataFrame:
    """Развернуть длинную таблицу замеров в матрицу время × станция.

    Столбцы возвращаются строго в порядке ``station_order`` — то есть в
    порядке движения по коридору, а не по номеру станции.
    """
    wide = df.pivot_table(index="timestamp", columns="station", values=value)
    missing = [s for s in station_order if s not in wide.columns]
    if missing:
        raise KeyError(f"нет данных по станциям: {missing}")
    return wide[station_order]
