@dataclass(frozen=True)
class Corridor:
    """Участок автомагистрали, на котором работаем.

    Границы заданы абсолютными постмилями (absolute postmile) — это
    непрерывная координата вдоль трассы из файла метаданных станций.
    """

    name: str
    freeway: int
    direction: str
    postmile_from: float
    postmile_to: float

    def __str__(self) -> str:  # pragma: no cover - косметика
        return (
            f"{self.name} (I-{self.freeway} {self.direction}, "
            f"PM {self.postmile_from}–{self.postmile_to})"
        )


# Рабочий коридор, выбранный по реальным данным (январь–апрель 2026).
#
# Изначально предполагалась I-405 — самый известный затор в США. Данные
# этот выбор отменили: из 114 станций основного хода I-405 South лишь 6
# имеют настоящие измерения, средняя наблюдаемость 7.7%. Всё остальное
# PeMS достраивает. Строить на этом прогноз нельзя.
#
# SR-210 West прошла отбор по двум условиям сразу: непрерывная цепочка
# исправных станций — и настоящий утренний затор, ради которого проект
# и затевался (свободный ход 8.0 мин, P50 8.8, P90 16.0, P95 20.8).
#
# Первая версия цепочки состояла из 15 станций (максимальный разрыв
# 1.24 мили) и была построена по январю. К середине февраля три из них
# замолчали навсегда — проверка на апреле это подтвердила. Цепочка
# сокращена до 12 станций: разрыв вырос до 1.84 мили, среднее время
# поездки изменилось на +0.12 мин, зато март и апрель снова пригодны.
#
# Подробности отбора — в docs/corridor-selection.md.
